"""Original redistributable fixtures, synthesized independently of the track solver.

The waveform uses analytic curved paths and a vectorized bisection solution of
retarded time; search receives rounded, sparse samples and uses PCHIP instead.
"""

import csv
import json
from pathlib import Path

import numpy as np

from .audio import write_wav


def analytic_path(name, t):
    t = np.asarray(t)
    if name == "A":
        tau = t - 45
        return np.stack(
            (85 * tau, 650 + 150 * np.sin(tau / 24), 1050 + 30 * np.sin(tau / 31)), axis=-1
        )
    tau = t - 145
    return np.stack((-500 + 350 * np.sin(tau / 36), 95 * tau, 1450 + 1.2 * tau), axis=-1)


def emission_times(name, arrival, observer, c):
    # The generation path is analytic; it never calls Track or SampledTrack.
    lo, hi = arrival - 300, arrival.copy()
    for _ in range(48):
        mid = (lo + hi) / 2
        residual = mid + np.linalg.norm(analytic_path(name, mid) - observer, axis=1) / c
        lo = np.where(residual < arrival, mid, lo)
        hi = np.where(residual >= arrival, mid, hi)
    return (lo + hi) / 2


def create_case(directory, seed=7, noise_only=False, source_drift_hz=0.0):
    if not np.isfinite(source_drift_hz) or abs(source_drift_hz) > 20:
        raise ValueError(
            "Synthetic source drift must be finite and between -20 and 20 Hz per 60 s."
        )
    if seed < 0:
        raise ValueError("Seed must be nonnegative.")
    directory = Path(directory)
    if directory.exists() and any(directory.iterdir()):
        raise ValueError(f"Use an empty output directory: {directory}")
    directory.mkdir(parents=True, exist_ok=True)
    fs, duration, offset, c = 4000, 200, 11.25, 343.0
    observer = np.array([137.0, -213.0, 0.0])
    t = np.arange(fs * duration) / fs
    rng = np.random.default_rng(seed)
    # Persistent hum and broadband noise make the signal-processing step meaningful.
    audio = 0.055 * rng.standard_normal(len(t)) + 0.06 * np.sin(2 * np.pi * 60 * t)
    for name, f0, center, window in [("A", 131, 45, (15, 75)), ("B", 173, 145, (115, 175))]:
        if noise_only:
            continue
        emission = emission_times(name, t + offset, observer, c)
        radius = np.linalg.norm(analytic_path(name, emission) - observer, axis=1)
        # Smooth taper outside the event; constant tone inside, unless drift is requested.
        gate = np.clip(np.minimum((t - window[0] + 8) / 8, (window[1] + 8 - t) / 8), 0, 1)
        gate = np.sin(np.pi * gate / 2) ** 2
        phase = 2 * np.pi * (f0 * emission + 0.5 * source_drift_hz / 60 * (emission - center) ** 2)
        audio += gate * (1000 / radius) * (0.10 * np.sin(phase) + 0.035 * np.sin(2 * phase))
    write_wav(directory / "recording.wav", fs, audio)
    with (directory / "tracks.csv").open("w", newline="", encoding="utf-8") as stream:
        writer = csv.writer(stream)
        writer.writerow(["track_id", "time_s", "east_m", "north_m", "up_m"])
        for name, bounds in [("A", (-20, 110)), ("B", (80, 220))]:
            ts = np.arange(*bounds, 2.0)
            xyz = np.round(analytic_path(name, ts), 1)
            for suffix, shift in [("", [0, 0, 0]), ("-decoy", [900, -650, 220])]:
                for stamp, pos in zip(ts, xyz + np.array(shift), strict=True):
                    writer.writerow([name + suffix, stamp, *pos])
    config = {
        "schema_version": 1,
        "title": "Two flyovers, one shared clock",
        "coordinate_system": "local_enu_m",
        "audio": "recording.wav",
        "tracks": "tracks.csv",
        "provenance": "Original fictional aircraft and audio generated by Argelius Doppler Lab; MIT.",
        "time_basis": "Fictional seconds. Track time = recording-relative arrival time + clock_offset_s.",
        "sound_speed_m_s": c,
        "max_track_gap_s": 3,
        "clock_offset_s": [9.25, 13.25, 0.5],
        "grid": {"east_m": [-800, 800, 100], "north_m": [-800, 800, 100], "up_m": 0},
        "spectrogram": {"window_s": 2, "hop_s": 0.5, "max_hz": 450},
        "events": [
            {
                "name": "Flyover 1",
                "start_s": 15,
                "end_s": 75,
                "source_hz": [129, 133, 0.5],
                "track_ids": ["A", "A-decoy"],
            },
            {
                "name": "Flyover 2",
                "start_s": 115,
                "end_s": 175,
                "source_hz": [171, 175, 0.5],
                "track_ids": ["B", "B-decoy"],
            },
        ],
    }
    (directory / "case.json").write_text(json.dumps(config, indent=2) + "\n", encoding="utf-8")
    truth = {
        "fixture": "synthetic",
        "seed": seed,
        "noise_only": noise_only,
        "source_drift_hz_per_60_s": source_drift_hz,
        "observer_enu_m": observer.tolist(),
        "clock_offset_s": offset,
        "track_ids": ["A", "B"],
        "source_hz": [131, 173],
        "note": "Evaluation only. The solver never reads this file. No real coordinates.",
    }
    (directory / "truth.json").write_text(json.dumps(truth, indent=2) + "\n", encoding="utf-8")
    return directory / "case.json"
